/** The two photos (start and end) for an exercise, or null. */
export const photosFor = (moveId: string) => (PHOTO[moveId] ? [0, 1].map((i) => `${BASE}/${PHOTO[moveId]}/${i}.jpg`) : null);

export type PhotoInfo = { instructions: string[]; primaryMuscles: string[]; secondaryMuscles: string[]; equipment: string | null; level: string };
const info = new Map<string, Promise<PhotoInfo | null>>();
/** Step by step instructions and muscles for a photographed exercise, fetched once. */
export function photoInfo(moveId: string): Promise<PhotoInfo | null> {
  const id = PHOTO[moveId];
  if (!id) return Promise.resolve(null);
  if (!info.has(id)) info.set(id, fetch(`${BASE}/${id}.json`).then((r) => (r.ok ? r.json() : null)).catch(() => null));
  return info.get(id)!;
}
